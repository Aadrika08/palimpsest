#!/usr/bin/env python3
"""Generate the MaleCNS v4 development-gate numbers quoted in the paper.

Reads only the retained S2 report (paper/evidence/male-v4-s2/report.json). Never launches
experiments. Every number is a count or a median over the 24 recorded owners.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
REPORT = PAPER / 'evidence/male-v4-s2/report.json'
OUTPUT = PAPER / 'generated/male-v4-development.tex'
SEEDS, ARMS, SCENES = (10, 11, 12), ('old-corpus', 'augmented'), 4


def compute(report: dict) -> dict:
    if report.get('route') != 'development' or report.get('status') != 'completed':
        raise ValueError('S2 report is not a completed development evaluation')
    admission = report['admission']
    if admission.get('status') != 'failed-gate' or admission.get('all_owners_normal') is not True:
        raise ValueError('unexpected S2 admission state')
    if admission.get('qualification_claims') != [] or report.get('qualification_claims') != []:
        raise ValueError('S2 report carries a qualification claim')
    cases = report['cases']
    rows = {arm: [v for v in cases.values() if v['case']['arm'] == arm] for arm in ARMS}
    if any(len(rows[arm]) != len(SEEDS) * SCENES for arm in ARMS):
        raise ValueError('S2 report does not hold 24 owners')
    goals = {f'{seed}:{arm}': sum(bool(v['goal_reached']) for v in rows[arm] if v['case']['training_seed'] == seed)
             for seed in SEEDS for arm in ARMS}
    if goals != admission['goals_by_seed_arm']:
        raise ValueError('recomputed goals disagree with the report admission block')
    if any(v['teacher_queries'] != 0 for v in cases.values()):
        raise ValueError('teacher query recorded')
    out = {'goals': goals, 'threshold': admission['threshold_per_augmented_seed']}
    for arm in ARMS:
        distances = [v['final_distance_metres'] for v in rows[arm]]
        out[arm] = {'goal': sum(bool(v['goal_reached']) for v in rows[arm]),
                    'stalled': sum(v['outcome'] == 'stalled' for v in rows[arm]),
                    'time_limit': sum(v['outcome'] == 'time_limit' for v in rows[arm]),
                    'median': statistics.median(distances)}
    return out


def render(v: dict) -> str:
    g = v['goals']
    lines = ['% Generated by scripts/build_male_v4_development.py; do not edit.',
             f'\\newcommand{{\\MaleVfourThreshold}}{{{v["threshold"]}}}',
             f'\\newcommand{{\\MaleVfourScenes}}{{{SCENES}}}',
             f'\\newcommand{{\\MaleVfourEpisodes}}{{{SCENES * len(SEEDS)}}}',
             f'\\newcommand{{\\MaleVfourAugGoals}}{{{v["augmented"]["goal"]}}}',
             f'\\newcommand{{\\MaleVfourAugStalled}}{{{v["augmented"]["stalled"]}}}',
             f'\\newcommand{{\\MaleVfourAugTimeLimit}}{{{v["augmented"]["time_limit"]}}}',
             f'\\newcommand{{\\MaleVfourAugMedianDistance}}{{{v["augmented"]["median"]:.1f}}}',
             f'\\newcommand{{\\MaleVfourOldGoals}}{{{v["old-corpus"]["goal"]}}}',
             f'\\newcommand{{\\MaleVfourOldMedianDistance}}{{{v["old-corpus"]["median"]:.1f}}}',
             f'\\newcommand{{\\MaleVfourOldBySeed}}{{{g["10:old-corpus"]}, {g["11:old-corpus"]}, {g["12:old-corpus"]}}}',
             f'\\newcommand{{\\MaleVfourAugBySeed}}{{{g["10:augmented"]}, {g["11:augmented"]}, {g["12:augmented"]}}}']
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(compute(json.loads(REPORT.read_text())))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit('male-v4-development.tex is missing or stale')
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
