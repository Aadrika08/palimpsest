#!/usr/bin/env python3
"""Generate the RQ5 affordability table from retained change-audit evidence.

Reads only the retained pilot accounting record. Never launches experiments.
The log(K/alpha) budget is certified with exact rational Taylor lower sums,
the same method as the Lean `ChangeAudit.Numerical` bridge and
`studies/change_audit_v1/check.py`: if sum_{k<=m} q^k/k! > K/alpha then
q > log(K/alpha). Scenario counts round up and radii round up, so every
reported number is conservative.
"""
from __future__ import annotations

import argparse
import json
import math
from fractions import Fraction
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ACCOUNTING = PAPER / 'evidence/change-audit-runtime-pilot-v1/source3c17cfd/pilot-process-accounting.json'
OUTPUT = PAPER / 'generated/audit-affordability.tex'

K, ALPHA = 3, Fraction(1, 20)            # three gain candidates vs gain 1; family-wise alpha
LOG_UPPER = Fraction(40944, 10000)       # certified below: q > log(60) = 4.09434...
PILOT_SCENARIOS, PILOT_CONDITIONS, PILOT_TICKS = 4, 16, 64
# Separately charged artifact audit (docs/reports/change-audit-runtime-pilot-v1-2026-11-05.md).
AUDIT_CHARGE = Fraction('2.658180')
AUDIT_LANE, TOTAL_ALLOCATION = Fraction(3600), Fraction(24 * 3600)
RADII = (Fraction(1, 5), Fraction(1, 10), Fraction(1, 20))


def certify_log_upper(q: Fraction, target: Fraction, terms: int = 40) -> None:
    total, term = Fraction(1), Fraction(1)
    for k in range(1, terms + 1):
        term = term * q / k
        total += term
    if not total > target:
        raise ValueError('Taylor lower sum does not certify the log budget')


def ceil_div(a: Fraction, b: Fraction) -> int:
    return math.ceil(a / b)


def radius_upper(n: int) -> Fraction:
    """Upper bound on sqrt(2 q / n), rounded up to 1e-3."""
    square = 2 * LOG_UPPER / n
    r = Fraction(math.ceil(math.sqrt(square) * 1000), 1000)
    while r * r < square:
        r += Fraction(1, 1000)
    return r


def compute(accounting: dict) -> dict:
    certify_log_upper(LOG_UPPER, K / ALPHA)
    run = accounting['accounting']
    if run['status'] != 'completed' or run['accounting_complete'] is not True or run['tree_drained'] is not True:
        raise ValueError('pilot accounting is not complete')
    if accounting['certified_improvement'] is not False:
        raise ValueError('unexpected improvement claim in pilot accounting')
    pilot = Fraction(str(accounting['pilot_process_cpu_seconds']))
    charged = Fraction(str(accounting['aggregate_audit_and_project_cpu_seconds'])) + AUDIT_CHARGE
    per_scenario = pilot / PILOT_SCENARIOS
    budgets = {'audit': AUDIT_LANE - charged, 'total': TOTAL_ALLOCATION - charged}
    affordable = {key: int(value // per_scenario) for key, value in budgets.items()}
    required = []
    for r in RADII:
        n = ceil_div(2 * LOG_UPPER, r * r)
        required.append((r, n, n * per_scenario / 3600))
    return dict(pilot=pilot, charged=charged, per_scenario=per_scenario, budgets=budgets,
                affordable=affordable, radius={k: radius_upper(n) for k, n in affordable.items()},
                required=required)


def fmt(x: Fraction, places: int) -> str:
    return f'{float(x):,.{places}f}'


def render(v: dict) -> str:
    lines = [
        '% Generated by scripts/build_audit_affordability.py; do not edit.',
        f'\\newcommand{{\\AuditPilotCpu}}{{{fmt(v["pilot"], 1)}}}',
        f'\\newcommand{{\\AuditChargedCpu}}{{{fmt(v["charged"], 1)}}}',
        f'\\newcommand{{\\AuditPerScenarioCpu}}{{{fmt(v["per_scenario"], 1)}}}',
        f'\\newcommand{{\\AuditLaneScenarios}}{{{v["affordable"]["audit"]}}}',
        f'\\newcommand{{\\AuditLaneRadius}}{{{fmt(v["radius"]["audit"], 3)}}}',
        f'\\newcommand{{\\AuditTotalScenarios}}{{{v["affordable"]["total"]}}}',
        f'\\newcommand{{\\AuditTotalRadius}}{{{fmt(v["radius"]["total"], 3)}}}',
        '\\newcommand{\\AuditRequiredRows}{%',
    ]
    for r, n, hours in v['required']:
        lines.append(f'{fmt(r, 2)} & {n:,} & {fmt(hours, 1)} \\\\')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(compute(json.loads(ACCOUNTING.read_text())))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit('audit-affordability.tex is missing or stale')
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
